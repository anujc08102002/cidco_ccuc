/* EnforceFlow SQL Server schema. Run in SSMS as a sysadmin or dbcreator account. */
IF DB_ID(N'EnforceFlow') IS NULL CREATE DATABASE EnforceFlow;
GO
USE EnforceFlow;
GO
CREATE SCHEMA enforcement;
GO
CREATE TABLE enforcement.Users (
  UserId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY,
  Username NVARCHAR(80) NOT NULL UNIQUE, DisplayName NVARCHAR(160) NOT NULL,
  PasswordHash NVARCHAR(255) NOT NULL, RoleCode NVARCHAR(30) NOT NULL,
  IsActive BIT NOT NULL DEFAULT 1, MustChangePassword BIT NOT NULL DEFAULT 0, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT CK_Users_Role CHECK (RoleCode IN ('surveyor','cuc','ccuc','legal','master'))
);
CREATE TABLE enforcement.Cases (
  CaseId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY,
  CaseNumber NVARCHAR(80) NOT NULL UNIQUE, PropertyReference NVARCHAR(250) NOT NULL, Sector NVARCHAR(80) NOT NULL,
  Node NVARCHAR(80) NOT NULL, OwnerName NVARCHAR(200) NOT NULL, SurveyReference NVARCHAR(80) NULL,
  CurrentStage TINYINT NOT NULL DEFAULT 1, Status NVARCHAR(30) NOT NULL DEFAULT 'In progress', LegalHold BIT NOT NULL DEFAULT 0,
  NoticeReference NVARCHAR(80) NULL, AssignedSurveyorId UNIQUEIDENTIFIER NULL, AssignedCucId UNIQUEIDENTIFIER NULL, ResponsibleUserId UNIQUEIDENTIFIER NULL,
  Latitude DECIMAL(10,7) NULL, Longitude DECIMAL(10,7) NULL, SiteAddress NVARCHAR(500) NULL, LocationSource NVARCHAR(60) NULL,
  LocationAccuracyMetres DECIMAL(10,2) NULL, LocationCapturedAt DATETIME2 NULL,
  IsArchived BIT NOT NULL DEFAULT 0, ArchivedAt DATETIME2 NULL, ArchiveUntil DATETIME2 NULL, ArchiveReason NVARCHAR(1000) NULL, ArchivedByUserId UNIQUEIDENTIFIER NULL,
  Priority NVARCHAR(20) NULL, ViolationDescription NVARCHAR(MAX) NULL, ApplicableSections NVARCHAR(80) NULL,
  NextActionAt DATETIME2 NULL, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), RowVersion ROWVERSION,
  CONSTRAINT CK_Cases_Stage CHECK (CurrentStage BETWEEN 1 AND 8),
  CONSTRAINT CK_Cases_Status CHECK (Status IN ('Overdue','In progress','Awaiting approval','Closed','Review hold')),
  CONSTRAINT CK_Cases_SiteCoordinates CHECK ((Latitude IS NULL AND Longitude IS NULL) OR (Latitude BETWEEN -90 AND 90 AND Longitude BETWEEN -180 AND 180)),
  CONSTRAINT FK_Cases_Surveyor FOREIGN KEY (AssignedSurveyorId) REFERENCES enforcement.Users(UserId),
  CONSTRAINT FK_Cases_Cuc FOREIGN KEY (AssignedCucId) REFERENCES enforcement.Users(UserId),
  CONSTRAINT FK_Cases_Responsible FOREIGN KEY (ResponsibleUserId) REFERENCES enforcement.Users(UserId)
);
CREATE INDEX IX_Cases_Node_Status ON enforcement.Cases(Node, Status);
CREATE INDEX IX_Cases_AssignedCuc ON enforcement.Cases(AssignedCucId);
CREATE TABLE enforcement.CaseActions (
  ActionId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY, CaseId UNIQUEIDENTIFIER NOT NULL,
  ActionType NVARCHAR(60) NOT NULL, Stage TINYINT NOT NULL, Notes NVARCHAR(MAX) NULL, PerformedByUserId UNIQUEIDENTIFIER NOT NULL,
  OccurredAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), CONSTRAINT FK_Actions_Case FOREIGN KEY (CaseId) REFERENCES enforcement.Cases(CaseId),
  CONSTRAINT FK_Actions_User FOREIGN KEY (PerformedByUserId) REFERENCES enforcement.Users(UserId)
);
CREATE TABLE enforcement.Surveys (
  SurveyId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY, CaseId UNIQUEIDENTIFIER NOT NULL,
  VisitAt DATETIME2 NULL, Latitude DECIMAL(10,7) NULL, Longitude DECIMAL(10,7) NULL, Measurements NVARCHAR(MAX) NULL, EncroachmentDetails NVARCHAR(MAX) NULL, Remarks NVARCHAR(MAX) NULL,
  SubmittedByUserId UNIQUEIDENTIFIER NOT NULL, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT FK_Surveys_Case FOREIGN KEY (CaseId) REFERENCES enforcement.Cases(CaseId), CONSTRAINT FK_Surveys_User FOREIGN KEY (SubmittedByUserId) REFERENCES enforcement.Users(UserId)
);
CREATE TABLE enforcement.Documents (
  DocumentId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY, CaseId UNIQUEIDENTIFIER NOT NULL,
  DocumentType NVARCHAR(50) NOT NULL, ReferenceNumber NVARCHAR(80) NULL, VersionNumber INT NOT NULL DEFAULT 1, FileName NVARCHAR(260) NULL, StorageKey NVARCHAR(500) NULL,
  IsPublished BIT NOT NULL DEFAULT 0, PublishedAt DATETIME2 NULL, DigitallySignedAt DATETIME2 NULL, CreatedByUserId UNIQUEIDENTIFIER NOT NULL, CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT FK_Documents_Case FOREIGN KEY (CaseId) REFERENCES enforcement.Cases(CaseId), CONSTRAINT FK_Documents_User FOREIGN KEY (CreatedByUserId) REFERENCES enforcement.Users(UserId)
);
CREATE INDEX IX_Documents_Public ON enforcement.Documents(IsPublished, PublishedAt) WHERE IsPublished = 1;
CREATE TABLE enforcement.Hearings (
  HearingId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY, CaseId UNIQUEIDENTIFIER NOT NULL, HearingAt DATETIME2 NOT NULL,
  Venue NVARCHAR(250) NULL, Status NVARCHAR(30) NOT NULL DEFAULT 'Scheduled', AttendanceNotes NVARCHAR(MAX) NULL, Proceedings NVARCHAR(MAX) NULL, CreatedByUserId UNIQUEIDENTIFIER NOT NULL,
  CONSTRAINT FK_Hearings_Case FOREIGN KEY (CaseId) REFERENCES enforcement.Cases(CaseId), CONSTRAINT FK_Hearings_User FOREIGN KEY (CreatedByUserId) REFERENCES enforcement.Users(UserId)
);
CREATE TABLE enforcement.LegalUpdates (
  LegalUpdateId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY, CaseId UNIQUEIDENTIFIER NOT NULL,
  LegalReference NVARCHAR(80) NULL, LegalStatus NVARCHAR(80) NOT NULL, CourtReference NVARCHAR(160) NULL, Notes NVARCHAR(MAX) NULL,
  SynchronizedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), SynchronizedByUserId UNIQUEIDENTIFIER NOT NULL,
  CONSTRAINT FK_Legal_Case FOREIGN KEY (CaseId) REFERENCES enforcement.Cases(CaseId), CONSTRAINT FK_Legal_User FOREIGN KEY (SynchronizedByUserId) REFERENCES enforcement.Users(UserId)
);
CREATE TABLE enforcement.DemolitionDrives (
  DemolitionDriveId UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID() PRIMARY KEY, CaseId UNIQUEIDENTIFIER NOT NULL, PlannedAt DATETIME2 NULL,
  CompletedAt DATETIME2 NULL, CoordinationNotes NVARCHAR(MAX) NULL, Outcome NVARCHAR(MAX) NULL, CreatedByUserId UNIQUEIDENTIFIER NOT NULL,
  CONSTRAINT FK_Demolition_Case FOREIGN KEY (CaseId) REFERENCES enforcement.Cases(CaseId), CONSTRAINT FK_Demolition_User FOREIGN KEY (CreatedByUserId) REFERENCES enforcement.Users(UserId)
);
CREATE TABLE enforcement.AuditLog (
  AuditId BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY, UserId UNIQUEIDENTIFIER NULL, EntityType NVARCHAR(60) NOT NULL, EntityId UNIQUEIDENTIFIER NULL,
  EventType NVARCHAR(80) NOT NULL, Detail NVARCHAR(MAX) NULL, OccurredAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), CorrelationId UNIQUEIDENTIFIER NULL,
  CONSTRAINT FK_Audit_User FOREIGN KEY (UserId) REFERENCES enforcement.Users(UserId)
);
GO
CREATE OR ALTER TRIGGER enforcement.TR_Cases_UpdatedAt ON enforcement.Cases AFTER UPDATE AS
BEGIN SET NOCOUNT ON; UPDATE c SET UpdatedAt=SYSUTCDATETIME() FROM enforcement.Cases c INNER JOIN inserted i ON c.CaseId=i.CaseId; END;
GO
